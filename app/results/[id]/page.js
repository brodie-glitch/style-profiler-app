"use client";
import { useEffect, useState } from "react";
import { useParams } from "next/navigation";

export default function Results() {
  const { id } = useParams();
  const [rec, setRec] = useState(null);
  const [missing, setMissing] = useState(false);

  useEffect(() => {
    fetch(`/api/results/${id}`)
      .then((r) => (r.ok ? r.json() : Promise.reject()))
      .then(setRec)
      .catch(() => setMissing(true));
  }, [id]);

  if (missing) return <div className="center"><div className="empty">Profile not found.</div></div>;
  if (!rec) return <div className="center"><p className="lead">Loading…</p></div>;

  const p = rec.profile;
  const topStyles = p.styles.slice(0, 6);
  const topAttrs = p.attrs.slice(0, 8);
  const gallery = rec.liked.slice(0, 9);

  function downloadReport() {
    const styles = topStyles.map((s) => `<tr><td>${s.name}</td><td style="text-align:right">${s.pct}%</td></tr>`).join("");
    const attrs = topAttrs.map((a) => `<li>${a.name} (${a.pct}%)</li>`).join("");
    const imgs = gallery.map((u) => `<img src="${u}" style="width:32%;border-radius:8px;margin:.5%">`).join("");
    const html = `<!doctype html><meta charset="utf-8"><title>Style profile — ${rec.clientName || "client"}</title>
<body style="font-family:Georgia,serif;max-width:720px;margin:40px auto;color:#1d1b18;padding:0 20px">
<h1 style="border-bottom:2px solid #2f6f5e;padding-bottom:8px">Style Profile</h1>
<p><b>Client:</b> ${rec.clientName || "—"}<br><b>Date:</b> ${new Date(rec.createdAt).toLocaleDateString()}<br><b>Liked:</b> ${rec.likedCount} of ${rec.ratedCount} images</p>
<h2>Top styles</h2><table style="width:100%;border-collapse:collapse">${styles}</table>
<h2>Defining qualities</h2><ul>${attrs}</ul>
<h2>Favourite images</h2><div>${imgs}</div>
<p style="color:#8a8377;font-size:12px;margin-top:40px">Generated by Style Profiler.</p></body>`;
    const blob = new Blob([html], { type: "text/html" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `style-profile-${(rec.clientName || "client").replace(/\s+/g, "-").toLowerCase()}.html`;
    a.click();
    URL.revokeObjectURL(a.href);
  }

  return (
    <>
      <div className="topbar">
        <span className="brand"><span className="dot" /> Style Profiler</span>
      </div>
      <h1>{rec.clientName || "Style profile"}</h1>
      <p className="lead">{new Date(rec.createdAt).toLocaleDateString()} · liked {rec.likedCount} of {rec.ratedCount} images</p>

      <div className="card">
        <h2 style={{ marginTop: 0 }}>Top styles</h2>
        {topStyles.length ? topStyles.map((s) => (
          <div className="bar" key={s.name}>
            <div className="lab"><span>{s.name}</span><span>{s.pct}%</span></div>
            <div className="track"><div className="fill" style={{ width: `${s.pct}%` }} /></div>
          </div>
        )) : <p className="lead">No clear preferences — try more ratings.</p>}

        <h2>Defining qualities</h2>
        <div>{topAttrs.length ? topAttrs.map((a) => <span className="pill" key={a.name}>{a.name} {a.pct}%</span>) : "—"}</div>
      </div>

      <h2>What they loved</h2>
      {gallery.length ? (
        <div className="gallery">{gallery.map((u, k) => <div className="g" key={k} style={{ backgroundImage: `url('${u}')` }} />)}</div>
      ) : <p className="lead">No images were liked.</p>}

      <div style={{ height: 18 }} />
      <button className="btn" onClick={downloadReport}>Download report</button>
      <div style={{ height: 8 }} />
      <button className="btn secondary noprint" onClick={() => window.print()}>Print / Save as PDF</button>
    </>
  );
}
